export const formatPrice = (value) => {
  if (value >= 1000000000) return `₦${(value / 1000000000).toFixed(2).replace(/\.00$/, '')}B`;
  if (value >= 1000000) return `₦${(value / 1000000).toFixed(value % 1000000 === 0 ? 0 : 1)}M`;
  return `₦${value.toLocaleString('en-NG')}`;
};
